import { CaptureUpdateAction } from "@excalidraw/excalidraw";
import { resetView, zoomStep } from "../canvas/focalZoom.js";
import { ARCHITECTURE_PACKS } from "../templates/architecturePacks.js";
import {
  COMMAND_CATEGORY_INSERT,
  COMMAND_CATEGORY_STUDIOS,
  COMMAND_CATEGORY_TEMPLATES,
  INFRASTRUCTURE_PROVIDER_GLYPHS,
  getInfrastructureInsertTargets,
} from "./engineeringCommandCatalog.js";

const MORE_TOOL_COMMANDS = [
  ["tools.insert-image", "Insert Image", "Tools", ["image", "picture", "insert image"], "", "image"],
  ["tools.frame", "Frame Tool", "Tools", ["frame", "frames"], "", "frame"],
  ["tools.web-embed", "Web Embed", "Tools", ["web", "embed", "iframe"], "", "embeddable"],
  ["tools.draw-to-shape", "Draw to Shape", "Tools", ["autoshape", "shape recognition"], "", "autoshape"],
  ["tools.laser", "Laser Pointer", "Tools", ["laser", "pointer", "presentation"], "", "laser"],
  ["tools.bucket-fill", "Bucket Fill", "Tools", ["bucket", "fill", "color"], "", "bucketfill"],
  ["tools.lasso", "Lasso Selection", "Tools", ["lasso", "select"], "", "lasso"],
];

export function createSketchiziCommandRegistry(context) {
  const {
    apiRef,
    canEdit,
    selectedCount,
    themeMode,
    setThemeMode,
    gridEnabled,
    toggleGrid,
    setMinimapOpen,
    fitDiagram,
    activateMoreTool,
    openPanel,
    startCollaboration,
    leaveOrEndCollaboration,
    requestEditAccess,
    collaborationRoom,
    collaborationPermission,
    currentFolder,
    fileActionsRef,
    reopenClosedTab,
    closedTabCount = 0,
    openKubernetesStudio,
    openDockerComposeStudio,
    toggleSystemDesignStudio,
    systemDesignStudioOpen = false,
    insertCatalogIcon,
    insertArchitecturePack,
    openArchitectureTemplates,
    openDesignTemplates,
  } = context;

  // Focal-point zoom: anchors on the active selection, else the last clicked canvas point.
  const updateZoom = (operation) => {
    const api = apiRef.current;
    if (!api) return;
    if (operation === "reset") resetView(api);
    else zoomStep(api, operation);
  };

  const commands = [];

  commands.push(
    ...MORE_TOOL_COMMANDS.map(([id, label, category, keywords, shortcut, tool]) => ({
      id,
      label,
      description: `Open the existing ${label.toLowerCase()} tool`,
      keywords,
      category,
      shortcut,
      icon: "◈",
      available: () => canEdit,
      execute: () => activateMoreTool(tool),
    })),
    {
      id: "tools.text-to-diagram",
      label: "Text to Diagram",
      description: "Open the existing Text to Diagram dialog",
      keywords: ["text", "diagram", "ai", "generate"],
      category: "Tools",
      shortcut: "",
      icon: "✿",
      available: () => canEdit,
      execute: () => activateMoreTool("text-to-diagram"),
    },
    {
      id: "tools.mermaid",
      label: "Mermaid to Excalidraw",
      description: "Open the existing Mermaid conversion dialog",
      keywords: ["mermaid", "diagram", "convert", "ai"],
      category: "Tools",
      shortcut: "",
      icon: "Y",
      available: () => canEdit,
      execute: () => activateMoreTool("mermaid"),
    },
    {
      id: "tools.wireframe-to-code",
      label: "Wireframe to Code",
      description: "Open the existing wireframe generation action",
      keywords: ["wireframe", "code", "magicframe", "ai"],
      category: "Tools",
      shortcut: "",
      icon: "✣",
      available: () => canEdit,
      execute: () => activateMoreTool("magicframe"),
    },
    {
      id: "tools.icon-library",
      label: "Open Icon Library",
      description: "Open Sketchizi's icon library",
      keywords: ["icon", "icons", "library", "cloud icons", "aws", "kubernetes icons", "uml", "mind map", "eraser"],
      category: "Tools",
      shortcut: "/",
      icon: "▧",
      available: () => canEdit,
      execute: () => openPanel("icon-library"),
    },
    {
      id: "properties.open",
      label: "Open Properties",
      description: "Open properties and style controls for the current selection",
      keywords: ["properties", "style", "appearance", "stroke", "fill"],
      category: "Tools",
      shortcut: "P",
      icon: "◧",
      available: () => canEdit && selectedCount > 0,
      contextual: () => selectedCount > 0,
      execute: () => openPanel("properties"),
    },
    {
      id: "view.zoom-in",
      label: "Zoom In",
      description: "Increase canvas zoom",
      keywords: ["zoom", "in", "magnify"],
      category: "View",
      shortcut: "Ctrl++",
      icon: "+",
      available: () => true,
      execute: () => updateZoom("in"),
    },
    {
      id: "view.zoom-out",
      label: "Zoom Out",
      description: "Decrease canvas zoom",
      keywords: ["zoom", "out", "shrink"],
      category: "View",
      shortcut: "Ctrl+-",
      icon: "−",
      available: () => true,
      execute: () => updateZoom("out"),
    },
    {
      id: "view.reset-zoom",
      label: "Reset Zoom",
      description: "Return canvas zoom to 100%",
      keywords: ["zoom", "reset", "100%"],
      category: "View",
      shortcut: "Ctrl+0",
      icon: "1:1",
      available: () => true,
      execute: () => updateZoom("reset"),
    },
    {
      id: "view.fit-canvas",
      label: "Fit to Canvas",
      description: "Fit the drawing into the viewport",
      keywords: ["fit", "canvas", "viewport", "diagram", "center", "center canvas", "show everything"],
      category: "View",
      shortcut: "F",
      icon: "□",
      available: () => true,
      execute: fitDiagram,
    },
    {
      id: "view.toggle-minimap",
      label: "Toggle Minimap",
      description: "Show or hide the canvas minimap",
      keywords: ["minimap", "map", "overview"],
      category: "View",
      shortcut: "M",
      icon: "▦",
      available: () => true,
      execute: () => setMinimapOpen((open) => !open),
    },
    {
      id: "view.toggle-theme",
      label: themeMode === "dark" ? "Switch to Light Theme" : "Switch to Dark Theme",
      description: "Toggle Sketchizi's light and dark theme",
      keywords: ["theme", "dark", "light", "appearance"],
      category: "View",
      shortcut: "D",
      icon: themeMode === "dark" ? "☀" : "☾",
      available: () => true,
      execute: () => setThemeMode((mode) => mode === "dark" ? "light" : "dark"),
    },
    {
      id: "view.toggle-grid",
      label: gridEnabled ? "Hide Grid" : "Show Grid",
      description: "Toggle Excalidraw's native grid and grid snapping",
      keywords: ["grid", "snap", "snapping", "canvas", "alignment"],
      category: "View",
      shortcut: "G",
      icon: "▦",
      available: () => true,
      execute: toggleGrid,
    },
    {
      id: "collaboration.start",
      label: "Start Collaboration",
      description: "Create a new collaboration room",
      keywords: ["collaboration", "collab", "room", "share"],
      category: "Collaboration",
      shortcut: "",
      icon: "◎",
      available: () => !collaborationRoom,
      execute: startCollaboration,
    },
    {
      id: "collaboration.open",
      label: "Open Collaboration",
      description: "Open the current collaboration details",
      keywords: ["collaboration", "collab", "details", "participants", "room"],
      category: "Collaboration",
      shortcut: "",
      icon: "◎",
      available: () => Boolean(collaborationRoom),
      contextual: () => Boolean(collaborationRoom),
      execute: startCollaboration,
    },
    {
      id: "collaboration.request-edit",
      label: "Request Edit Access",
      description: "Ask the host to grant editing permission",
      keywords: ["edit", "access", "permission", "request", "viewer"],
      category: "Collaboration",
      shortcut: "",
      icon: "→",
      available: () => Boolean(collaborationRoom) && collaborationPermission === "viewer",
      contextual: () => Boolean(collaborationRoom) && collaborationPermission === "viewer",
      execute: requestEditAccess,
    },
    {
      id: "collaboration.leave-or-end",
      label: collaborationPermission === "host" ? "End Collaboration" : "Leave Collaboration",
      description: collaborationPermission === "host" ? "End the current collaboration session" : "Leave the current collaboration session",
      keywords: ["collaboration", "collab", "leave", "end", "disconnect"],
      category: "Collaboration",
      shortcut: "",
      icon: "×",
      available: () => Boolean(collaborationRoom),
      contextual: () => Boolean(collaborationRoom),
      execute: leaveOrEndCollaboration,
    },
    {
      id: "files.new",
      label: "New",
      description: "Create a new drawing using the existing file action",
      keywords: ["new", "file", "drawing", "blank"],
      category: "Files",
      shortcut: "",
      icon: "+",
      available: () => canEdit,
      execute: () => fileActionsRef.current.createNewFile?.(),
    },
    {
      id: "files.open",
      label: "Open",
      description: "Open a drawing using the existing file action",
      keywords: ["open", "load", "file", "drawing"],
      category: "Files",
      shortcut: "Ctrl+O",
      icon: "↥",
      available: () => canEdit,
      execute: () => fileActionsRef.current.openDrawingFromDisk?.(),
    },
    {
      id: "files.save",
      label: "Save",
      description: "Save the current drawing using the existing file action",
      keywords: ["save", "write", "file", "persist"],
      category: "Files",
      shortcut: "Ctrl+S",
      icon: "↓",
      available: () => canEdit,
      execute: () => fileActionsRef.current.saveCurrentDrawing?.(),
    },
    {
      id: "files.save-as",
      label: "Save As",
      description: "Save the current drawing to a new file",
      keywords: ["save", "save as", "export file", "file"],
      category: "Files",
      shortcut: "Ctrl+Shift+S",
      icon: "↓",
      available: () => canEdit,
      execute: () => fileActionsRef.current.saveDrawingAs?.(),
    },
    {
      id: "files.reopen-closed-tab",
      label: "Reopen Closed Tab",
      description: "Restore the most recently closed canvas from Local Drafts",
      keywords: ["reopen", "restore", "undo close", "closed tab", "recently closed", "local drafts"],
      category: "Files",
      shortcut: "Ctrl+Shift+T",
      icon: "↺",
      available: () => closedTabCount > 0,
      execute: () => reopenClosedTab?.(),
    },
    {
      id: "files.open-folder",
      label: "Open Folder",
      description: "Choose a folder for Sketchizi file browsing",
      keywords: ["folder", "directory", "open folder", "files"],
      category: "Files",
      shortcut: "",
      icon: "▰",
      available: () => canEdit,
      execute: () => fileActionsRef.current.openFolderFromDisk?.(),
    },
    {
      id: "files.close-folder",
      label: "Close Folder",
      description: "Close the current Sketchizi folder",
      keywords: ["folder", "directory", "close"],
      category: "Files",
      shortcut: "",
      icon: "▰",
      available: () => canEdit && Boolean(currentFolder),
      execute: () => fileActionsRef.current.closeCurrentFolder?.(),
    },
    {
      id: "studios.kubernetes",
      label: "Open Kubernetes Studio",
      description: "Author, validate and export Kubernetes YAML",
      keywords: ["kubernetes", "k8s", "studio", "yaml", "helm", "manifest", "kube", "export yaml"],
      category: COMMAND_CATEGORY_STUDIOS,
      shortcut: "",
      icon: "⎈",
      available: () => typeof openKubernetesStudio === "function",
      execute: () => openKubernetesStudio?.(),
    },
    {
      id: "studios.docker-compose",
      label: "Open Docker Compose Studio",
      description: "Edit, validate and diagram Docker Compose projects",
      keywords: ["docker", "compose", "studio", "container", "yaml", "docker-compose", "services"],
      category: COMMAND_CATEGORY_STUDIOS,
      shortcut: "",
      icon: "▣",
      available: () => typeof openDockerComposeStudio === "function",
      execute: () => openDockerComposeStudio?.(),
    },
    {
      id: "studios.system-design",
      label: systemDesignStudioOpen ? "Close System Design Studio" : "Open System Design Studio",
      description: "Drag-and-drop system design primitives with live traffic and latency simulation",
      keywords: ["system design", "architecture", "traffic", "latency", "simulate", "load balancer", "cache", "studio"],
      category: COMMAND_CATEGORY_STUDIOS,
      shortcut: "",
      icon: "◫",
      available: () => typeof toggleSystemDesignStudio === "function",
      execute: () => toggleSystemDesignStudio?.(),
    },
    ...getInfrastructureInsertTargets().map((target) => ({
      id: target.id,
      label: target.label,
      description: target.description,
      keywords: target.keywords,
      category: COMMAND_CATEGORY_INSERT,
      shortcut: "",
      icon: INFRASTRUCTURE_PROVIDER_GLYPHS[target.provider] || "◈",
      available: () => canEdit && typeof insertCatalogIcon === "function",
      execute: () => insertCatalogIcon(target.icon),
    })),
    {
      id: "templates.architecture-packs",
      label: "Browse Architecture Packs",
      description: "Open curated starter packs for cloud and system design",
      keywords: ["templates", "packs", "starter", "architecture", "browse"],
      category: COMMAND_CATEGORY_TEMPLATES,
      shortcut: "",
      icon: "◫",
      available: () => canEdit && typeof openArchitectureTemplates === "function",
      execute: () => openArchitectureTemplates?.(),
    },
    {
      id: "templates.design-catalog",
      label: "Browse Design Templates",
      description: "Open the template catalog for AWS, system design, flows and patterns",
      keywords: ["templates", "catalog", "design", "aws", "patterns", "flows", "new design"],
      category: COMMAND_CATEGORY_TEMPLATES,
      shortcut: "",
      icon: "◇",
      available: () => canEdit && typeof openDesignTemplates === "function",
      execute: () => openDesignTemplates?.(),
    },
    ...ARCHITECTURE_PACKS.map((pack) => ({
      id: `templates.pack.${pack.id}`,
      label: `Insert Pack: ${pack.title}`,
      description: pack.description,
      keywords: ["template", "pack", "starter", "insert", "load", pack.category, pack.badge, pack.id.replace(/-/g, " ")].filter(Boolean),
      category: COMMAND_CATEGORY_TEMPLATES,
      shortcut: "",
      icon: "◫",
      available: () => canEdit && typeof insertArchitecturePack === "function",
      execute: () => insertArchitecturePack(pack),
    })),
    {
      id: "application.shortcuts",
      label: "Keyboard Shortcuts",
      description: "Open Sketchizi's keyboard shortcut reference",
      keywords: ["help", "shortcuts", "keyboard", "keys", "reference"],
      category: "Application",
      shortcut: "?",
      icon: "?",
      available: () => true,
      execute: () => openPanel("shortcuts"),
    },
  );

  return commands;
}
